create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'student' check (role in ('student','teacher')),
  created_at timestamptz not null default now()
);

create table if not exists public.game_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  client_id text not null,
  player text not null default 'Murid',
  mode text not null default 'Individu',
  game text not null,
  topic text not null,
  points integer not null default 0 check (points >= 0),
  correct integer not null default 0 check (correct between 0 and 5),
  played_on text,
  created_at timestamptz not null default now(),
  unique(user_id, client_id)
);

alter table public.profiles enable row level security;
alter table public.game_results enable row level security;

-- Pengguna hanya boleh membaca profil sendiri. Tiada polisi untuk pengguna menukar role sendiri.
drop policy if exists "profile read own" on public.profiles;
create policy "profile read own" on public.profiles for select to authenticated using (id = auth.uid());

-- Murid boleh membaca/menambah rekod milik sendiri.
drop policy if exists "results read own or teacher" on public.game_results;
create policy "results read own or teacher" on public.game_results for select to authenticated using (user_id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
drop policy if exists "results insert own" on public.game_results;
create policy "results insert own" on public.game_results for insert to authenticated with check (user_id = auth.uid());
drop policy if exists "results update own" on public.game_results;
create policy "results update own" on public.game_results for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());

-- Profil automatik diwujudkan apabila akaun didaftarkan.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, display_name, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name',''), 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
